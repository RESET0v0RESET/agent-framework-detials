DOC_EXTENSIONS = {".md", ".mdx", ".rst", ".adoc"}

GENERATED_MARKERS = (
    "Generated by",
    "Code generated",
    "DO NOT EDIT",
    "Auto-generated",
    "This file is generated",
)


def is_excluded_filename(path: Path) -> bool:
    name = path.name
    lower = name.lower()
    suffixes = path.suffixes

    if path.suffix.lower() in DOC_EXTENSIONS or lower.endswith(".ipynb"):
        return True
    if lower == "conftest.py":
        return True
    if lower.endswith(".min.js"):
        return True

    if lower.startswith(("test_", "tests_", "example_", "examples_", "demo_", "tutorial_", "benchmark_")):
        return True
    if lower.endswith(("_test.py", "_tests.py", "_example.py", "_demo.py", "_tutorial.py", "_benchmark.py")):
        return True
    if lower.startswith(("mock_", "fake_", "dummy_", "stub_")):
        return True
    if lower.endswith(("_mock.py", "_fake.py", "_dummy.py", "_stub.py")):
        return True

    if len(suffixes) >= 2:
        joined = "".join(s.lower() for s in suffixes[-2:])
        if joined in {
            ".test.ts",
            ".test.tsx",
            ".test.js",
            ".test.jsx",
            ".spec.ts",
            ".spec.tsx",
            ".spec.js",
            ".spec.jsx",
        }:
            return True

    if name.endswith(("Test.java", "Tests.java", "_test.go", "_spec.rb")):
        return True

    return False


def is_generated_file(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", errors="ignore") as f:
            head = f.read(4096)
    except Exception:
        return False
    return any(marker in head for marker in GENERATED_MARKERS)


def is_excluded_path(path: Path, repo_dir: Path) -> bool:
    rel_parts = [part.lower() for part in path.relative_to(repo_dir).parts[:-1]]
    if any(part in NON_IMPL_DIR_PARTS for part in rel_parts):
        return True
    if is_excluded_filename(path):
        return True
    if is_generated_file(path):
        return True
    return False


def iter_py_files(repo_dir: Path, exclude_non_impl_paths: bool = False) -> Iterable[Path]:
    for root, dirs, files in os.walk(repo_dir):
        dirs[:] = [
            d
            for d in dirs
            if d.lower() not in SKIP_DIRS
            and not d.startswith(".")
            and not d.lower().endswith(("venv", "env"))
            and (not exclude_non_impl_paths or d.lower() not in NON_IMPL_DIR_PARTS)
        ]
        for name in files:
            if not name.endswith(".py"):
                continue
            path = Path(root) / name
            if exclude_non_impl_paths and is_excluded_path(path, repo_dir):
                continue
            yield path


MOCK_LIKE_RE = re.compile(r"^(mock|fake|dummy|stub)(_|[A-Z]).*|.*(Mock|Fake|Dummy|Stub)(Agent|Tool|LLM|Memory)$")


def is_mock_like_name(name: str | None) -> bool:
    return bool(name and MOCK_LIKE_RE.match(name))
